"""Generate `docs/GLOBAL_CENSUS_COLUMNS.md` from the schemas (never edit that file by hand).

    python tools/generate_column_docs.py

Reads `schemas/global_schema.json` (the global columns), `schemas/global_equivalents.json` (local -> global renames and the period patterns),
`derived_columns.py` (copy / sum / rate rules that create global columns from local ones) and every `countries/*/schema/*_schema.json`
(which source of which country declares which feature) and writes, per global column: category, definition, type, unit, denominator,
resampling, and which country sources supply it (directly, through an equivalent, or through a derived rule). Ends with a coverage matrix
(global columns x countries) and a list of global columns that no source supplies yet -- the work list for a census-research agent.
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "pycensus"
sys.path.insert(0, str(ROOT / "src"))


def _prefix_matches(prefix: str, source: str) -> bool:
    return bool(prefix) and (source == prefix or source.startswith(prefix) or prefix in source or prefix.startswith(source))


def main() -> None:
    glob = json.loads((SRC / "schemas" / "global_schema.json").read_text(encoding="utf-8"))
    eq = json.loads((SRC / "schemas" / "global_equivalents.json").read_text(encoding="utf-8"))
    names = [g["feature_name"] for g in glob]
    dup = sorted({n for n in names if names.count(n) > 1})

    schemas = []   # (country, source, feature set)
    for p in sorted((SRC / "countries").glob("*/schema/*_schema.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        schemas.append((d.get("country") or p.parts[-3], d.get("source") or p.stem.replace("_schema", ""), {f["feature_name"] for f in d.get("features", [])}))

    def locate(local: str):
        """(country, source) pairs whose schema declares the feature behind the local column name `prefix_feature`."""
        hits = set()
        for country, source, feats in schemas:
            for f in feats:
                if local.endswith("_" + f) and _prefix_matches(local[: -len(f) - 1], source):
                    hits.add((country, source))
        return hits

    supply = defaultdict(lambda: defaultdict(set))   # global -> country -> {how}
    for country, source, feats in schemas:
        for f in feats:
            if f in names:
                supply[f][country].add(f"{source}")
    for local, g in eq["equivalents"].items():
        for country, source in locate(local):
            supply[g][country].add(f"{source} ({local.split('_', 1)[-1] if local.endswith('_' + local.split('_')[-1]) else local})")
    for g, regexes in eq.get("latest_patterns", {}).items():   # period-carrying columns (elections): any schema feature matching a pattern supplies the global column
        for country, source, feats in schemas:
            if any(re.fullmatch(r"(?:[A-Za-z0-9]+_)?(?:%s)" % rx, f) for rx in regexes for f in feats):
                supply[g][country].add(f"{source} (latest period)")
    try:
        from pycensus import derived_columns as dc
        for g, cols in list(dc._COPY_RULES) + list(dc._SUM_RULES) + [(a, (b,)) for a, b, *_ in dc._RATE_RULES]:
            for c in cols:
                for country, source in locate(c):
                    supply[g][country].add(f"{source} (derived)")
    except Exception as exc:   # the generator must still work when the package cannot be imported
        print("derived rules not read:", exc)

    countries = sorted({c for c, _, _ in schemas})
    cats = []
    for g in glob:
        if g["category"] not in cats:
            cats.append(g["category"])
    out = ["# Global census columns", "",
           "*Generated by `tools/generate_column_docs.py` from `src/pycensus/schemas/` -- do not edit by hand; run the tool after changing a schema.*", "",
           "Every city-science city ends up with the same column names for the same concept (the **global schema**). A source's own columns keep their "
           "prefixed names (`acs5_povertyBelow100`) and the global column repeats the value under the shared name (`povertyPopulation`); "
           "see `AGENT_GUIDE_NEW_CITY_OR_COUNTRY.md` for how to add a country, source or column.", "",
           "**Types**: `count` (summable), `mean`/`rate`/`index` (intensive). **Resampling** columns: `up` = fine -> coarse level, `down` = coarse -> fine (weighted by the named column). "
           "**Denominator** = the column the share is relative to (`.relative`).", ""]
    if dup:
        out += [f"> Duplicate entries in `global_schema.json`: {', '.join(dup)} (remove one).", ""]
    out += [f"{len(set(names))} global columns, {len(countries)} countries with schemas: {', '.join(countries)}.", ""]
    for cat in cats:
        out += [f"## {cat}", "", "| Column | Definition | Type / unit | Denominator | Resampling (up / down, weight) | Supplied by |", "|---|---|---|---|---|---|"]
        for g in glob:
            if g["category"] != cat:
                continue
            n = g["feature_name"]
            sup = "; ".join(f"**{c}**: " + ", ".join(sorted(h)) for c, h in sorted(supply[n].items())) or "*nobody yet*"
            tu = g.get("type", "") + (f" / {g['unit']}" if g.get("unit") else "")
            rs = f"{g.get('resampling_up', '')} / {g.get('resampling_down', '')}" + (f", {g['resampling_weight']}" if g.get("resampling_weight") else "")
            out.append(f"| `{n}` | {g.get('definition', '').replace('|', '/')} | {tu} | {g.get('relative_to', '') or ''} | {rs} | {sup} |")
        out.append("")
    out += ["## Coverage matrix", "", "| Column | " + " | ".join(countries) + " |", "|---|" + "---|" * len(countries)]
    for n in dict.fromkeys(names):
        out.append(f"| `{n}` | " + " | ".join("x" if c in supply[n] else "" for c in countries) + " |")
    out += ["", "## Global columns no source supplies yet", ""]
    yb = [n for n in dict.fromkeys(names) if n.startswith("dwellings_built_")]   # filled by year_built.py from any construction-year columns, not by a schema feature
    none = [n for n in dict.fromkeys(names) if not supply[n] and n not in yb]
    out += [f"- `{n}`" for n in none] or ["(none)"]
    out += ["", f"`{'`, `'.join(yb)}` are not listed above: `year_built.py` computes them from any source that has construction-year counts (see `schemas/year_built_bands.json`)."]
    out.append("")
    (ROOT / "docs" / "GLOBAL_CENSUS_COLUMNS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/GLOBAL_CENSUS_COLUMNS.md: {len(set(names))} columns, {len(none)} with no supplier")


if __name__ == "__main__":
    main()
