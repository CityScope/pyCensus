"""Loader for the City of Toronto "Neighbourhood Profiles" (Statistics Canada 2021 Census aggregated to the 158 social-planning
neighbourhoods), returning a common-schema GeoDataFrame at level ``neighbourhood``.

Technical aspects:
    Used where StatCan's own dissemination-area tables cannot be reached (statcan.gc.ca answers 403 / "website unavailable" to some
    networks). Both inputs come from the City of Toronto open-data CKAN portal (``ckan0.cf.opendata.inter.prod-toronto.ca``, keyless):
    the 2021 profile workbook (one row per characteristic, one column per neighbourhood) and the neighbourhood boundaries (EPSG:4326
    GeoJSON). ``schema/toronto_schema.json`` (generated by :mod:`.build_schema`) lists every exposed characteristic with the workbook
    row(s) it comes from (``codes`` = ``"<section title>||<row label>"``; several codes are summed, a leading ``-`` subtracts).

    Columns named like a pycensus global-schema feature are returned bare (``population``, ``households``, ...); every other one is
    prefixed ``statcan_`` (it is Statistics Canada 2021 Census data).
"""
from __future__ import annotations
from pycensus.cache import get_data_dir

import hashlib
import io
import json
import re
from pathlib import Path
from typing import Optional

import geopandas as gpd
import numpy as np
import pandas as pd
import requests

PACKAGE_URL = "https://ckan0.cf.opendata.inter.prod-toronto.ca/api/3/action/package_show?id="
_SCHEMA = Path(__file__).resolve().parent.parent / "schema" / "toronto_schema.json"
DEFAULT_DATA_DIR = str(get_data_dir("canada"))  # env/temp default, resolved at import


def _download(url: str, path: Path) -> Path:
    if path.exists() and path.stat().st_size > 0:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    r = requests.get(url, timeout=300, headers={"User-Agent": "Mozilla/5.0"})
    r.raise_for_status()
    path.write_bytes(r.content)
    return path


def _resource_url(package: str, pattern: str) -> str:
    r = requests.get(PACKAGE_URL + package, timeout=60)
    r.raise_for_status()
    for res in r.json()["result"]["resources"]:
        if re.search(pattern, res["name"]):
            return res["url"]
    raise LookupError(f"No resource matching {pattern!r} in Toronto open-data package {package!r}")


def _norm(text: str) -> str:
    return text.replace("’", "'").strip()


def _profile_rows(xlsx: Path) -> tuple[list, dict]:
    """``(neighbourhood numbers, {(section, label): float array})`` -- first occurrence of a (section, label) pair wins."""
    import openpyxl

    ws = openpyxl.load_workbook(xlsx, read_only=True, data_only=True).worksheets[0]
    rows = [r for r in ws.iter_rows(values_only=True)]
    numbers = [str(int(float(v))) for v in rows[1][1:] if v not in (None, "")]
    n = len(numbers)
    table, section = {}, ""
    for r in rows[3:]:
        label = r[0] or ""
        if not label:
            continue
        vals = pd.to_numeric(pd.Series(list(r[1:1 + n])), errors="coerce").to_numpy(dtype=float)
        if not label.startswith(" "):
            section = _norm(label)
            table.setdefault((section, section), vals)
            table.setdefault(("", section), vals)
        else:
            table.setdefault((section, _norm(label)), vals)
    return numbers, table


def _features(table: dict, n: int, geoids: list) -> pd.DataFrame:
    """Schema features from a {(section, label): values} table (sums, subtractions for codes starting with '-')."""
    from pycensus.canonical import global_feature_names

    GLOBAL_FEATURES = global_feature_names()
    schema = json.loads(_SCHEMA.read_text(encoding="utf-8"))["features"]
    out = {"GEOID": geoids}
    for f in schema:
        total = np.zeros(n)
        ok = True
        for code in f["codes"]:
            sign = -1.0 if code.startswith("-") else 1.0
            sec, _, label = code.lstrip("-").partition("||")
            vals = table.get((_norm(sec), _norm(label)))
            if vals is None:
                ok = False
                break
            total = total + sign * np.nan_to_num(vals, nan=0.0)
        if ok:
            name = f["feature_name"]
            out[name if name in GLOBAL_FEATURES else f"statcan_{name}"] = total
    return pd.DataFrame(out)


def _da_table(canada_dir: str, dauids: list) -> tuple[list, dict]:
    """Per-dissemination-area values of every Census Profile characteristic, keyed like `_profile_rows` ((section, label) -> array)."""
    import csv
    import zipfile

    zpath = Path(canada_dir) / "raw" / "census_profile" / "98-401-X2021006_Ontario_eng_CSV.zip"
    member = "98-401-X2021006_English_CSV_data_Ontario.csv"
    cache = Path(canada_dir) / "raw" / "census_profile" / f"da_values_{hashlib.md5(','.join(sorted(dauids)).encode()).hexdigest()[:10]}.parquet"
    zf = zipfile.ZipFile(zpath)
    # characteristic id -> (section, label) from the Canada block (identical order in every block)
    ids, section, key_by_id = [], "", {}
    with zf.open(member) as f:
        rd = csv.reader(io.TextIOWrapper(f, encoding="latin-1"))
        next(rd)
        first = None
        for r in rd:
            first = first or r[1]
            if r[1] != first:
                break
            cid, label = int(r[8]), r[9]
            if not label.startswith(" "):
                section = _norm(label)
                key_by_id.setdefault(cid, []).extend([(section, section), ("", section)])
            else:
                key_by_id.setdefault(cid, []).append((section, _norm(label)))
    wanted = {cid for cid in key_by_id}
    if cache.exists():
        long = pd.read_parquet(cache)
    else:
        want_da = set(dauids)
        parts = []
        with zf.open(member) as f:
            for ch in pd.read_csv(f, encoding="latin-1", usecols=["ALT_GEO_CODE", "GEO_LEVEL", "CHARACTERISTIC_ID", "C1_COUNT_TOTAL"],
                                  dtype={"ALT_GEO_CODE": str, "GEO_LEVEL": str}, chunksize=2_000_000):
                ch = ch[ch["GEO_LEVEL"] == "Dissemination area"]
                ch = ch[ch["ALT_GEO_CODE"].isin(want_da)]
                if len(ch):
                    parts.append(ch[["ALT_GEO_CODE", "CHARACTERISTIC_ID", "C1_COUNT_TOTAL"]])
        long = pd.concat(parts, ignore_index=True)
        long["C1_COUNT_TOTAL"] = pd.to_numeric(long["C1_COUNT_TOTAL"], errors="coerce")
        long.to_parquet(cache)
    wide = long.pivot_table(index="ALT_GEO_CODE", columns="CHARACTERISTIC_ID", values="C1_COUNT_TOTAL", aggfunc="first")
    geoids = [g for g in dauids if g in wide.index]
    wide = wide.reindex(geoids)
    table: dict = {}
    for cid, keys in key_by_id.items():
        if cid in wide.columns:
            for k in keys:
                table.setdefault(k, wide[cid].to_numpy(dtype=float))
    return geoids, table


def load(aoi: Optional[gpd.GeoDataFrame] = None, level: str = "neighbourhood", cache_dir: Optional[str] = None, data_dir: Optional[str] = None,
         canada_dir: Optional[str] = None, **_ignored) -> gpd.GeoDataFrame:
    """Toronto neighbourhoods (or, with the Ontario Census Profile on disk, dissemination areas) with every schema characteristic.

    Args:
        aoi: Area of interest (GeoDataFrame).
        level: ``"neighbourhood"`` or ``"dissemination-area"``.
        cache_dir: Cache folder; ``None`` = the pycensus cache.
        data_dir: Folder of the raw downloads; ``None`` = the pycensus cache.
        canada_dir: Folder of the Canada census downloads.
        **_ignored: Ignored.

    Returns:
        GeoDataFrame (EPSG:4326).
    """
    if level == "dissemination-area":
        from .. import geography as _geo

        w, s_, e, n = aoi.to_crs(4326).total_bounds
        _geo._AOI_BBOX = (float(w) - 0.02, float(s_) - 0.02, float(e) + 0.02, float(n) + 0.02)
        das = _geo._load_arcgis("dissemination-area", "35", canada_dir)
        das["GEOID"] = das["DAUID"].astype(str) if "DAUID" in das.columns else das["GEOID"].astype(str)
        geoids, table = _da_table(canada_dir, das["GEOID"].tolist())
        df = _features(table, len(geoids), geoids)
        res = das[["GEOID", "geometry"]].merge(df, on="GEOID", how="inner")
        res = res[res.intersects(aoi.to_crs(4326).union_all())] if aoi is not None else res
        return gpd.GeoDataFrame(res.reset_index(drop=True), geometry="geometry", crs=4326)
    if level not in ("neighbourhood", "tract", "blockgroup", "municipality"):
        raise ValueError(f"Toronto profile has the 'neighbourhood' and 'dissemination-area' levels, not {level!r}")
    base = get_data_dir("canada", data_dir) / "raw" / "toronto_profile"
    xlsx = base / "nbhd_2021_census_profile_full_158model.xlsx"
    if not xlsx.exists():
        _download(_resource_url("neighbourhood-profiles", r"2021.*158"), xlsx)
    geo = base / "neighbourhoods_4326.geojson"
    if not geo.exists():
        _download(_resource_url("neighbourhoods", r"^Neighbourhoods - 4326\.geojson$"), geo)

    numbers, table = _profile_rows(xlsx)
    df = _features(table, len(numbers), numbers)
    g = gpd.read_file(geo).to_crs(4326)
    code_col = next(c for c in ("AREA_SHORT_CODE", "AREA_LONG_CODE", "AREA_ID") if c in g.columns)
    g["GEOID"] = g[code_col].astype(str).str.lstrip("0")
    res = g[["GEOID", "geometry"]].merge(df, on="GEOID", how="inner")
    if aoi is not None and not res.empty:
        res = res[res.intersects(aoi.to_crs(4326).union_all())]
    return gpd.GeoDataFrame(res.reset_index(drop=True), geometry="geometry", crs=4326)


__all__ = ["load"]
